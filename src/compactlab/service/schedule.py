"""Calibration intervals and the OS scheduler files (launchd LaunchAgent, systemd user units).

Only text is generated here. `install` writes the unit files into the user's own LaunchAgents or systemd user folder,
after the caller has shown the diff and had it confirmed; it never runs launchctl or systemctl.
"""

from __future__ import annotations

import difflib
import re
import shlex
import sys
from dataclasses import dataclass
from pathlib import Path
from xml.sax.saxutils import escape

UNITS = {"s": 1, "m": 60, "h": 3600, "d": 86400, "w": 7 * 86400}
MIN_EVERY_S = 60
MARKER = "generated by compactlab schedule"
LABEL = "com.compactlab.agent"


def parse_every(text: str) -> float | None:
    """'6h', '1d', '90m', '2w', '45s' -> seconds; 'off' -> None (manual only). At least 60 s."""
    t = text.strip().lower()
    if t in ("off", "never", "manual", "0"):
        return None
    m = re.fullmatch(r"(\d+(?:\.\d+)?)\s*([smhdw])", t)
    if not m:
        raise ValueError(f"interval {text!r}: use a number with s, m, h, d or w (e.g. 6h, 1d, 7d), or 'off'")
    secs = float(m.group(1)) * UNITS[m.group(2)]
    if secs < MIN_EVERY_S:
        raise ValueError(f"interval {text!r} is under {MIN_EVERY_S} s")
    return secs


def fmt_every(secs: float | None) -> str:
    if secs is None:
        return "off"
    for u in ("w", "d", "h", "m"):
        if secs >= UNITS[u] and secs % UNITS[u] == 0:
            return f"{int(secs // UNITS[u])}{u}"
    return f"{int(secs)}s"


def backoff(every: float | None, failures: int, base: float = 300.0) -> float:
    """Wait after `failures` consecutive failed runs: 5 min doubling, never longer than the interval (or 1 day)."""
    cap = every if every is not None else 86400.0
    return min(cap, base * 2 ** max(failures - 1, 0))


def next_due(every: float | None, last_ok: float | None, last_attempt: float | None, failures: int,
             now: float) -> float | None:  # fmt: skip
    """When the next scheduled calibration is due (epoch seconds), or None when scheduling is off.

    Never calibrated: now. After a failure: the last attempt plus the backoff. Otherwise the last success plus the
    interval.
    """
    if every is None:
        return None
    if failures and last_attempt is not None:
        return last_attempt + backoff(every, failures)
    if last_ok is None:
        return now
    return last_ok + every


def is_stale(calibrated_at: float | None, every: float | None, now: float) -> bool:
    """A result is stale once it is older than twice the interval (1 day when scheduling is off)."""
    if calibrated_at is None:
        return True
    return now - calibrated_at > 2 * (every if every is not None else 86400.0)


# ---------- OS scheduler files ----------


@dataclass
class UnitFile:
    path: Path
    text: str


def _cmd(mode: str, every: float | None, extra: list[str]) -> list[str]:
    base = [sys.executable, "-m", "compactlab.cli.main"]
    if mode == "serve":
        return [*base, "serve", "--every", fmt_every(every), *extra]
    return [*base, "recalibrate", *extra]


def launchd_units(mode: str, every: float | None, extra: list[str], home: Path) -> list[UnitFile]:
    """One LaunchAgent: `serve` kept alive, or `recalibrate` run every interval (low priority, background)."""
    args = "".join(f"\n    <string>{escape(a)}</string>" for a in _cmd(mode, every, extra))
    log = home / ".compactlab" / "service" / "launchd.log"
    timing = (
        "  <key>RunAtLoad</key><true/>\n  <key>KeepAlive</key><dict><key>SuccessfulExit</key><false/></dict>\n"
        if mode == "serve"
        else f"  <key>StartInterval</key><integer>{int(every or 86400)}</integer>\n"
    )
    text = f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- {MARKER}; remove with: compactlab schedule uninstall --yes -->
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>{LABEL}</string>
  <key>ProgramArguments</key>
  <array>{args}
  </array>
{timing}  <key>ProcessType</key><string>Background</string>
  <key>LowPriorityIO</key><true/>
  <key>Nice</key><integer>10</integer>
  <key>StandardOutPath</key><string>{escape(str(log))}</string>
  <key>StandardErrorPath</key><string>{escape(str(log))}</string>
</dict>
</plist>
"""
    return [UnitFile(home / "Library" / "LaunchAgents" / f"{LABEL}.plist", text)]


def systemd_units(mode: str, every: float | None, extra: list[str], home: Path) -> list[UnitFile]:
    """A user service (`serve`, restarted on failure) or a oneshot `recalibrate` service plus a timer."""
    d = home / ".config" / "systemd" / "user"
    cmd = " ".join(shlex.quote(a) for a in _cmd(mode, every, extra))
    if mode == "serve":
        svc = f"""# {MARKER}; remove with: compactlab schedule uninstall --yes
[Unit]
Description=compactlab calibration service (localhost only)

[Service]
ExecStart={cmd}
Restart=on-failure
RestartSec=300
Nice=10
IOSchedulingClass=idle

[Install]
WantedBy=default.target
"""
        return [UnitFile(d / "compactlab.service", svc)]
    svc = f"""# {MARKER}; remove with: compactlab schedule uninstall --yes
[Unit]
Description=compactlab recalibration (one run)

[Service]
Type=oneshot
ExecStart={cmd}
Nice=10
IOSchedulingClass=idle
"""
    timer = f"""# {MARKER}; remove with: compactlab schedule uninstall --yes
[Unit]
Description=compactlab recalibration every {fmt_every(every or 86400)}

[Timer]
OnBootSec=15min
OnUnitActiveSec={int(every or 86400)}s
Persistent=true

[Install]
WantedBy=timers.target
"""
    return [UnitFile(d / "compactlab.service", svc), UnitFile(d / "compactlab.timer", timer)]


def units(platform: str, mode: str, every: float | None, extra: list[str], home: Path) -> list[UnitFile]:
    if mode not in ("serve", "recalibrate"):
        raise ValueError("mode must be serve or recalibrate")
    if mode == "recalibrate" and every is None:
        raise ValueError("a scheduled recalibrate needs an interval (not 'off')")
    return (launchd_units if platform == "launchd" else systemd_units)(mode, every, extra, home)


def diff(units_: list[UnitFile]) -> str:
    out: list[str] = []
    for u in units_:
        old = u.path.read_text() if u.path.exists() else ""
        out += difflib.unified_diff(old.splitlines(True), u.text.splitlines(True), f"{u.path} (current)", str(u.path))
    return "".join(out) or "(no change)\n"


def install(units_: list[UnitFile]) -> list[Path]:
    """Writes the unit files (only under the user's LaunchAgents / systemd user folder). Refuses to overwrite a
    file compactlab did not generate."""
    for u in units_:
        if u.path.exists() and MARKER not in u.path.read_text():
            raise PermissionError(f"{u.path} exists and was not generated by compactlab; not overwriting")
    for u in units_:
        u.path.parent.mkdir(parents=True, exist_ok=True)
        u.path.write_text(u.text)
    return [u.path for u in units_]


def installed(platform: str, home: Path) -> list[Path]:
    paths = (
        [home / "Library" / "LaunchAgents" / f"{LABEL}.plist"]
        if platform == "launchd"
        else [home / ".config" / "systemd" / "user" / n for n in ("compactlab.service", "compactlab.timer")]
    )
    return [p for p in paths if p.exists() and MARKER in p.read_text()]


def uninstall(platform: str, home: Path) -> list[Path]:
    gone = installed(platform, home)
    for p in gone:
        p.unlink()
    return gone


def activation_hint(platform: str) -> str:
    if platform == "launchd":
        return f"load it yourself: launchctl bootstrap gui/$(id -u) ~/Library/LaunchAgents/{LABEL}.plist"
    return "enable it yourself: systemctl --user daemon-reload && systemctl --user enable --now compactlab.timer"
